-- grant above covers every column on insert, which is the only way this one is ever written. And
-- it is deliberately absent from that table's column-level UPDATE grant, which 0016 made, so
-- Postgres refuses an update that would move an article from one Company Profile to the whole
-- Catalogue or the other way about. See docs/adr/0024, and `db/testing/ingest-role-check.sql`,
-- which refuses the grant if it ever appears.
--
-- The role must be exactly what the migrations say, on whatever database this runs against,
-- including the real Supabase project where the tests never run. The same check
-- `0016_news_for_the_catalogue` ends with, over the seven tables ingest now writes rather than
-- the six it did.
DO $$
DECLARE
  ingest_role oid := (SELECT oid FROM pg_roles WHERE rolname = 'rolodeck_ingest');
  broader text;
BEGIN
  SELECT string_agg(format('%I.%I', n.nspname, c.relname), ', ' ORDER BY n.nspname, c.relname)
  INTO broader
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')
    AND n.nspname IN ('public', 'auth')
    AND NOT (n.nspname = 'public' AND c.relname IN ('profiles', 'news_items', 'news_articles', 'news_profile_coverage', 'news_profile_site_recovery', 'events', 'event_attendances'))
    AND (
      has_table_privilege(ingest_role, c.oid, 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER')
      OR has_any_column_privilege(ingest_role, c.oid, 'SELECT, INSERT, UPDATE, REFERENCES')
    );

  IF broader IS NOT NULL THEN
    RAISE EXCEPTION 'rolodeck_ingest may hold no privilege beyond its seven tables, but can reach %', broader;
  END IF;

  -- Nothing on the new table beyond the select and insert granted above: no DELETE, no UPDATE of
  -- any column, and no TRUNCATE, which does not consult RLS at all.
  IF has_table_privilege(ingest_role, 'public.news_profile_site_recovery', 'DELETE, TRUNCATE, UPDATE, REFERENCES, TRIGGER')
    OR has_any_column_privilege(ingest_role, 'public.news_profile_site_recovery', 'UPDATE, REFERENCES')
  THEN
    RAISE EXCEPTION 'rolodeck_ingest may only select and insert news_profile_site_recovery, but holds more';
  END IF;

  -- And no update of the column that says which Company Profile a search found an article for.
  IF has_column_privilege(ingest_role, 'public.news_articles', 'searched_for_profile_id', 'UPDATE') THEN
    RAISE EXCEPTION 'rolodeck_ingest may not update news_articles.searched_for_profile_id';
  END IF;
END
