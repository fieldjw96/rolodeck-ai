-- The role must be exactly what the migrations say, on whatever database this runs against,
-- including the real Supabase project where the tests never run. The same shape of check
-- `0008_ingest_role` ends with, over the six tables ingest now writes rather than the four it
-- did. What this migration takes away — the right to execute anything at all — is checked by
-- `db/testing/ingest-role-check.sql` instead, for the reason the end of this block gives.
DO $$
DECLARE
  ingest_role oid := (SELECT oid FROM pg_roles WHERE rolname = 'rolodeck_ingest');
  broader text;
BEGIN
  SELECT string_agg(format('%I.%I', n.nspname, c.relname), ', ' ORDER BY n.nspname, c.relname)
  INTO broader
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relkind IN ('r', 'p', 'v', 'm', 'f')
    AND n.nspname IN ('public', 'auth')
    AND NOT (n.nspname = 'public' AND c.relname IN ('profiles', 'news_items', 'news_articles', 'news_profile_coverage', 'events', 'event_attendances'))
    AND (
      has_table_privilege(ingest_role, c.oid, 'SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER')
      OR has_any_column_privilege(ingest_role, c.oid, 'SELECT, INSERT, UPDATE, REFERENCES')
    );

  IF broader IS NOT NULL THEN
    RAISE EXCEPTION 'rolodeck_ingest may hold no privilege beyond its six tables, but can reach %', broader;
  END IF;

  -- TRUNCATE and DELETE on the new tables: neither is ingest's to make, and TRUNCATE does not
  -- consult RLS at all.
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname)
  INTO broader
  FROM pg_class c
  JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE n.nspname = 'public'
    AND c.relname IN ('news_articles', 'news_profile_coverage')
    AND has_table_privilege(ingest_role, c.oid, 'DELETE, TRUNCATE, REFERENCES, TRIGGER');

  IF broader IS NOT NULL THEN
    RAISE EXCEPTION 'rolodeck_ingest may only select, insert and update News, but holds more on %', broader;
  END IF;

  -- There is deliberately no check here on what the role may execute, although that is what
  -- this migration takes away. `db/testing/ingest-role-check.sql` makes it, and only against a
  -- freshly migrated scratch Postgres: a real Supabase project is full of SECURITY DEFINER
  -- functions that Postgres makes executable by PUBLIC, in schemas this repo never created, and
  -- a check on those would fail the production migration over something it did not grant. Same
  -- reason the guard in `0008_ingest_role` looks only at `public` and `auth`.
END
$$;
